export function dailyFortune(userId,now=new Date()) {
  const day=seoulDate(now),days=Math.floor(Date.parse(day+'T00:00:00Z')/86400000);
  let offset=0;for(const character of String(userId))offset=(Math.imul(offset,31)+character.codePointAt(0))>>>0;
  const index=((days+offset)%messages.length+messages.length)%messages.length;
  const [theme,message,practice]=messages[index];
  return {day,index,theme,message,practice};
}
